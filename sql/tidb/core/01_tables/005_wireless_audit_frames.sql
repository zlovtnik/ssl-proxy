CREATE TABLE IF NOT EXISTS WIRELESS_AUDIT_FRAMES (
    FRAME_PK          BIGINT       NOT NULL AUTO_INCREMENT,
    BATCH_ID          VARCHAR(128) NOT NULL,
    ROW_SEQUENCE      INT          NOT NULL,
    EVENT_TYPE        VARCHAR(64)  NOT NULL,
    OBSERVED_AT       TIMESTAMP(6) NOT NULL,
    SENSOR_ID         VARCHAR(64)  NOT NULL,
    LOCATION_ID       VARCHAR(128) NOT NULL,
    INTERFACE         VARCHAR(32)  NOT NULL,
    CHANNEL           SMALLINT     NOT NULL,
    BAND              VARCHAR(8)   NOT NULL,
    FRAME_TYPE        VARCHAR(32)  DEFAULT NULL,
    FRAME_SUBTYPE     VARCHAR(32)  NOT NULL,
    BSSID             VARCHAR(17)  DEFAULT NULL,
    SOURCE_MAC        VARCHAR(17)  DEFAULT NULL,
    DESTINATION_MAC   VARCHAR(17)  DEFAULT NULL,
    TRANSMITTER_MAC   VARCHAR(17)  DEFAULT NULL,
    RECEIVER_MAC      VARCHAR(17)  DEFAULT NULL,
    DESTINATION_BSSID VARCHAR(17)  DEFAULT NULL,
    SSID              VARCHAR(256) DEFAULT NULL,
    SIGNAL_DBM        SMALLINT     DEFAULT NULL,
    SEQUENCE_NUMBER   INT          DEFAULT NULL,
    RAW_LEN           INT          NOT NULL,
    IS_RETRY          TINYINT(1)   DEFAULT 0 NOT NULL,
    IS_MORE_DATA      TINYINT(1)   DEFAULT 0 NOT NULL,
    IS_POWER_SAVE     TINYINT(1)   DEFAULT 0 NOT NULL,
    IS_PROTECTED      TINYINT(1)   DEFAULT 0 NOT NULL,
    IS_TO_DS          TINYINT(1)   DEFAULT 0 NOT NULL,
    IS_FROM_DS        TINYINT(1)   DEFAULT 0 NOT NULL,
    IS_HANDSHAKE      TINYINT(1)   DEFAULT 0 NOT NULL,
    SECURITY_FLAGS    INT          DEFAULT 0 NOT NULL,
    DEVICE_ID         VARCHAR(128) DEFAULT NULL,
    USERNAME          VARCHAR(256) DEFAULT NULL,
    IDENTITY_SOURCE   VARCHAR(64)  DEFAULT 'unknown' NOT NULL,
    TAGS              VARCHAR(2000) DEFAULT NULL,
    ANOMALY_REASONS   VARCHAR(1000) DEFAULT NULL,
    RAW_JSON          JSON         DEFAULT NULL,
    CREATED_AT        TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (FRAME_PK),
    UNIQUE KEY WIRELESS_AUDIT_FRAMES_BATCH_UQ (BATCH_ID, ROW_SEQUENCE),
    KEY WIRELESS_FRAMES_SENSOR_TIME_IDX (SENSOR_ID, OBSERVED_AT),
    KEY WIRELESS_FRAMES_LOCATION_TIME_IDX (LOCATION_ID, OBSERVED_AT),
    KEY WIRELESS_FRAMES_SOURCE_MAC_IDX (SOURCE_MAC, OBSERVED_AT),
    KEY WIRELESS_FRAMES_BSSID_IDX (BSSID, OBSERVED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
