CREATE TABLE IF NOT EXISTS PROXY_EVENTS (
    ID                   BIGINT       NOT NULL AUTO_INCREMENT,
    BATCH_ID             VARCHAR(36)  NOT NULL,
    ROW_SEQUENCE         INT          NOT NULL,
    EVENT_TIME           TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    EVENT_TIMESTAMP_UTC  TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    EVENT_TYPE           VARCHAR(32)  NOT NULL,
    HOST                 VARCHAR(253) NOT NULL,
    PEER_IP              VARCHAR(45)  DEFAULT NULL,
    WG_PUBKEY            VARCHAR(64)  DEFAULT NULL,
    DEVICE_ID            BINARY(16)   DEFAULT NULL,
    IDENTITY_SOURCE      VARCHAR(16)  DEFAULT 'unknown',
    PEER_HOSTNAME        VARCHAR(253) DEFAULT NULL,
    CLIENT_UA            VARCHAR(512) DEFAULT NULL,
    BYTES_UP             BIGINT       DEFAULT 0,
    BYTES_DOWN           BIGINT       DEFAULT 0,
    STATUS_CODE          INT          DEFAULT NULL,
    BLOCKED              TINYINT(1)   DEFAULT 0,
    OBFUSCATION_PROFILE  VARCHAR(32)  DEFAULT NULL,
    CORRELATION_ID       BINARY(16)   DEFAULT NULL,
    PARENT_EVENT_ID      BIGINT       DEFAULT NULL,
    EVENT_SEQUENCE       INT          DEFAULT NULL,
    DURATION_MS          BIGINT       DEFAULT NULL,
    REASON               VARCHAR(64)  DEFAULT NULL,
    RAW_JSON             JSON         DEFAULT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY PROXY_EVENTS_BATCH_ROW_IDX (BATCH_ID, ROW_SEQUENCE),
    KEY PROXY_EVENTS_EVENT_UTC_IDX (EVENT_TIMESTAMP_UTC),
    KEY PROXY_EVENTS_TIME_IDX (EVENT_TIME DESC),
    KEY PROXY_EVENTS_HOST_IDX (HOST, EVENT_TIME),
    KEY PROXY_EVENTS_BLOCKED_IDX (BLOCKED, EVENT_TIME DESC),
    KEY PROXY_EVENTS_DEVICE_TIME_IDX (DEVICE_ID, EVENT_TIME DESC),
    KEY PROXY_EVENTS_WG_PUBKEY_TIME_IDX (WG_PUBKEY, EVENT_TIME DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
