-- object: wireless_bandwidth_windows
-- depends_on:

CREATE TABLE IF NOT EXISTS WIRELESS_BANDWIDTH_WINDOWS (
    BW_PK                BIGINT       NOT NULL AUTO_INCREMENT,
    BATCH_ID             VARCHAR(128) NOT NULL,
    ROW_SEQUENCE         INT          NOT NULL,
    SCHEMA_VERSION       SMALLINT     DEFAULT 1 NOT NULL,
    WINDOW_START         TIMESTAMP(6) NOT NULL,
    WINDOW_END           TIMESTAMP(6) NOT NULL,
    SENSOR_ID            VARCHAR(64)  NOT NULL,
    LOCATION_ID          VARCHAR(128) NOT NULL,
    INTERFACE            VARCHAR(32)  NOT NULL,
    CHANNEL              SMALLINT     NOT NULL,
    BAND                 VARCHAR(8)   NOT NULL,
    SOURCE_MAC           VARCHAR(17)  NOT NULL,
    DESTINATION_BSSID    VARCHAR(17)  NOT NULL,
    SSID                 VARCHAR(256) DEFAULT NULL,
    BYTES                BIGINT       DEFAULT 0 NOT NULL,
    FRAME_COUNT          BIGINT       DEFAULT 0 NOT NULL,
    RETRY_COUNT          BIGINT       DEFAULT 0 NOT NULL,
    MORE_DATA_COUNT      BIGINT       DEFAULT 0 NOT NULL,
    POWER_SAVE_COUNT     BIGINT       DEFAULT 0 NOT NULL,
    STRONGEST_SIGNAL_DBM SMALLINT     DEFAULT NULL,
    HIST_UNDER_100       BIGINT       DEFAULT 0 NOT NULL,
    HIST_100_500         BIGINT       DEFAULT 0 NOT NULL,
    HIST_500_1000        BIGINT       DEFAULT 0 NOT NULL,
    HIST_1000_1500       BIGINT       DEFAULT 0 NOT NULL,
    INTER_ARRIVAL_P50_MS INT          DEFAULT NULL,
    EXTERNAL_BSSID       TINYINT(1)   DEFAULT 0 NOT NULL,
    THRESHOLD_EXCEEDED   TINYINT(1)   DEFAULT 0 NOT NULL,
    WALL_CLOCK_DELTA_MS  BIGINT       DEFAULT NULL,
    WINDOW_IS_PARTIAL    TINYINT(1)   DEFAULT 0 NOT NULL,
    PUBLISHED_AT         TIMESTAMP(6) DEFAULT NULL,
    CREATED_AT           TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (BW_PK),
    UNIQUE KEY WIRELESS_BW_WINDOWS_BATCH_UQ (BATCH_ID, ROW_SEQUENCE),
    KEY WIRELESS_BW_SENSOR_TIME_IDX (SENSOR_ID, WINDOW_START),
    KEY WIRELESS_BW_THRESHOLD_IDX (THRESHOLD_EXCEEDED, WINDOW_START),
    KEY WIRELESS_BW_SOURCE_MAC_IDX (SOURCE_MAC, WINDOW_START),
    CONSTRAINT WIRELESS_BW_WINDOWS_RANGE_CK CHECK (WINDOW_END >= WINDOW_START)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
