-- object: octopus_core_proxy_evidence
-- depends_on: octopus_core_proxy_search_indexes
-- Adding the identity rewrites retained rows and indexes under ACCESS EXCLUSIVE.
-- Populated upgrades require a measured row budget and an approved window via
-- executor PGOPTIONS; see docs/proxy-rag-evidence-preparation.md. Fresh installs
-- need no window. Keep the rewrite and index build in one timed statement.
DO $$
DECLARE
  row_budget_text text := current_setting('sslproxy.proxy_evidence_max_rows', true);
  window_end_text text := current_setting('sslproxy.proxy_evidence_window_end', true);
  row_budget bigint;
  retained_rows bigint;
  statement_budget interval := current_setting('statement_timeout')::interval;
BEGIN
  IF EXISTS (SELECT 1 FROM pg_attribute
      WHERE attrelid = 'octopus_core.proxy_events'::regclass
        AND attname = 'observation_revision' AND NOT attisdropped)
      AND to_regclass('octopus_core.proxy_events_observation_revision_uq') IS NOT NULL THEN
    RETURN;
  END IF;
  -- Fail promptly if live traffic has not drained for the approved window.
  PERFORM set_config('lock_timeout', '1s', true);
  LOCK TABLE octopus_core.proxy_events IN ACCESS EXCLUSIVE MODE;
  -- Another executor may have completed the upgrade while this one waited.
  IF EXISTS (SELECT 1 FROM pg_attribute
      WHERE attrelid = 'octopus_core.proxy_events'::regclass
        AND attname = 'observation_revision' AND NOT attisdropped)
      AND to_regclass('octopus_core.proxy_events_observation_revision_uq') IS NOT NULL THEN
    RETURN;
  END IF;
  IF EXISTS (SELECT 1 FROM octopus_core.proxy_events) THEN
    IF row_budget_text IS NULL OR row_budget_text !~ '^[0-9]{1,18}$'
        OR NULLIF(window_end_text, '') IS NULL THEN
      RAISE EXCEPTION 'proxy evidence upgrade requires reviewed proxy_evidence_max_rows and proxy_evidence_window_end';
    END IF;
    row_budget := row_budget_text::bigint;
    IF statement_budget <= interval '1 second'
        OR NOT isfinite(window_end_text::timestamptz)
        OR clock_timestamp() + statement_budget > window_end_text::timestamptz THEN
      RAISE EXCEPTION 'proxy evidence upgrade requires finite statement_timeout > 1s within the maintenance window';
    END IF;
    SELECT count(*) INTO retained_rows FROM (
      SELECT 1 FROM octopus_core.proxy_events LIMIT row_budget + 1
    ) bounded;
    IF retained_rows > row_budget THEN
      RAISE EXCEPTION 'proxy evidence retained rows exceed reviewed maintenance budget %', row_budget;
    END IF;
    RAISE NOTICE 'proxy evidence maintenance: retained_rows=%, statement_timeout=%, lock_timeout=1s, window_end=%',
      retained_rows, statement_budget, window_end_text;
  END IF;
  -- Arrival-order cursor, distinct from event time and payload checksums.
  ALTER TABLE octopus_core.proxy_events
    ADD COLUMN IF NOT EXISTS observation_revision bigint GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN IF NOT EXISTS evidence jsonb NOT NULL DEFAULT '{}'::jsonb;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='octopus_core.proxy_events'::regclass AND conname='proxy_events_evidence_object_ck') THEN
    ALTER TABLE octopus_core.proxy_events ADD CONSTRAINT proxy_events_evidence_object_ck CHECK (jsonb_typeof(evidence)='object');
  END IF;
  CREATE UNIQUE INDEX IF NOT EXISTS proxy_events_observation_revision_uq
    ON octopus_core.proxy_events (observation_revision);
END $$;

-- Durable late-arrival/correction notification, written in the source commit.
-- No FK: source retention is independent. Missing sources get a disposition.
CREATE TABLE IF NOT EXISTS octopus_core.proxy_preparation_dirty (
  event_id varchar(64) PRIMARY KEY,
  source_revision bigint NOT NULL CHECK (source_revision > 0),
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS proxy_preparation_dirty_revision_idx
  ON octopus_core.proxy_preparation_dirty (source_revision, event_id);

CREATE SEQUENCE IF NOT EXISTS octopus_core.proxy_window_revision_seq;
CREATE TABLE IF NOT EXISTS octopus_core.proxy_window_dirty (
  window_start timestamptz NOT NULL,
  host varchar(1024) NOT NULL,
  device_key varchar(64) NOT NULL DEFAULT '',
  revision bigint NOT NULL DEFAULT nextval('octopus_core.proxy_window_revision_seq'),
  disposition varchar(32) NOT NULL DEFAULT 'pending',
  observed_rows_lower_bound integer,
  PRIMARY KEY (window_start, host, device_key)
);

CREATE TABLE IF NOT EXISTS octopus_core.proxy_preparation_progress (
  scope varchar(128) PRIMARY KEY,
  after_revision bigint NOT NULL DEFAULT 0 CHECK (after_revision >= 0),
  after_key varchar(255) NOT NULL DEFAULT '',
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
