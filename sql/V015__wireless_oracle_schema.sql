CREATE OR REPLACE VIEW VW_WL_ACTIVE_THREATS AS
SELECT
    THREAT_TYPE,
    SEVERITY,
    EVENT_AT,
    SENSOR_ID,
    LOCATION_ID,
    PRIMARY_MAC,
    SSID,
    BYTES,
    ALERT_PK,
    ACKNOWLEDGED
FROM (
    SELECT
        'rogue_ap' AS THREAT_TYPE,
        'HIGH' AS SEVERITY,
        DETECTED_AT AS EVENT_AT,
        SENSOR_ID,
        LOCATION_ID,
        ROGUE_BSSID AS PRIMARY_MAC,
        SSID,
        CAST(NULL AS NUMBER(20,0)) AS BYTES,
        ALERT_PK,
        ACKNOWLEDGED
    FROM WL_ALERT_ROGUE_AP
    WHERE ACKNOWLEDGED = 0
    UNION ALL
    SELECT
        'deauth_flood',
        'HIGH',
        DETECTED_AT,
        SENSOR_ID,
        LOCATION_ID,
        ATTACKER_MAC,
        TARGET_SSID,
        CAST(NULL AS NUMBER(20,0)),
        ALERT_PK,
        ACKNOWLEDGED
    FROM WL_ALERT_DEAUTH_FLOOD
    WHERE ACKNOWLEDGED = 0
    UNION ALL
    SELECT
        'bandwidth_threshold',
        'CRITICAL',
        FIRST_WINDOW_START,
        SENSOR_ID,
        LOCATION_ID,
        SOURCE_MAC,
        SSID,
        TOTAL_BYTES,
        ALERT_PK,
        ACKNOWLEDGED
    FROM WL_BW_ALERTS
    WHERE ACKNOWLEDGED = 0
    UNION ALL
    SELECT
        'signal_anomaly',
        'MEDIUM',
        DETECTED_AT,
        SENSOR_ID,
        LOCATION_ID,
        SOURCE_MAC,
        SSID,
        CAST(NULL AS NUMBER(20,0)),
        ALERT_PK,
        ACKNOWLEDGED
    FROM WL_ALERT_SIGNAL_ANOMALY
    WHERE ACKNOWLEDGED = 0
    UNION ALL
    SELECT
        'pmf_attack',
        'MEDIUM',
        DETECTED_AT,
        SENSOR_ID,
        LOCATION_ID,
        TARGET_MAC,
        SSID,
        CAST(NULL AS NUMBER(20,0)),
        ALERT_PK,
        ACKNOWLEDGED
    FROM WL_ALERT_PMF_ATTACK
    WHERE ACKNOWLEDGED = 0
)
ORDER BY
    CASE SEVERITY WHEN 'CRITICAL' THEN 1 WHEN 'HIGH' THEN 2 ELSE 3 END,
    EVENT_AT DESC;

CREATE OR REPLACE VIEW VW_WL_BW_DAILY_SUMMARY AS
SELECT
    TRUNC(CAST(WINDOW_START AS DATE)) AS TRAFFIC_DATE,
    SENSOR_ID,
    LOCATION_ID,
    SOURCE_MAC,
    DESTINATION_BSSID,
    SSID,
    EXTERNAL_BSSID,
    SUM(BYTES) AS TOTAL_BYTES,
    SUM(FRAME_COUNT) AS TOTAL_FRAMES,
    SUM(RETRY_COUNT) AS TOTAL_RETRIES,
    MAX(STRONGEST_SIGNAL_DBM) AS MAX_SIGNAL_DBM,
    MIN(STRONGEST_SIGNAL_DBM) AS MIN_SIGNAL_DBM,
    COUNT(*) AS WINDOW_COUNT,
    SUM(CASE WHEN THRESHOLD_EXCEEDED = 1 THEN 1 ELSE 0 END)
        AS THRESHOLD_EXCEEDED_COUNT,
    AVG(WALL_CLOCK_DELTA_MS) AS AVG_SENSOR_LAG_MS
FROM WL_BW_WINDOWS
GROUP BY
    TRUNC(CAST(WINDOW_START AS DATE)),
    SENSOR_ID, LOCATION_ID, SOURCE_MAC,
    DESTINATION_BSSID, SSID, EXTERNAL_BSSID;

