CREATE OR REPLACE PROCEDURE WL_PURGE_OLD_PARTITIONS (
    p_retain_months IN NUMBER DEFAULT 24
)
AS
    v_cutoff DATE := ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -p_retain_months);
    v_should_drop NUMBER(1,0);
BEGIN
    FOR rec IN (
        SELECT table_name, partition_name, high_value
        FROM   user_tab_partitions
        WHERE  table_name IN ('WL_AUDIT_FRAMES', 'WL_BW_WINDOWS')
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE
                'SELECT CASE WHEN ' || rec.high_value ||
                ' <= TO_TIMESTAMP_TZ(''' || TO_CHAR(v_cutoff, 'YYYY-MM-DD') ||
                ' 00:00:00 UTC'', ''YYYY-MM-DD HH24:MI:SS TZR'') THEN 1 ELSE 0 END FROM DUAL'
            INTO v_should_drop;
            IF v_should_drop = 1 THEN
                EXECUTE IMMEDIATE 'ALTER TABLE ' || rec.table_name ||
                    ' DROP PARTITION ' || rec.partition_name ||
                    ' UPDATE GLOBAL INDEXES';
            END IF;
        EXCEPTION
            WHEN OTHERS THEN NULL;
        END;
    END LOOP;
    COMMIT;
END WL_PURGE_OLD_PARTITIONS;
