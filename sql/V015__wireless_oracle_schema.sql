CREATE OR REPLACE PROCEDURE WL_BW_MERGE_ALERTS (
    p_batch_id IN VARCHAR2
)
AS
BEGIN
    MERGE INTO WL_BW_ALERTS tgt
    USING (
        WITH batch_keys AS (
            SELECT DISTINCT
                SENSOR_ID,
                SOURCE_MAC,
                DESTINATION_BSSID,
                TRUNC(CAST(WINDOW_START AS DATE)) AS ALERT_DATE
            FROM WL_BW_WINDOWS
            WHERE BATCH_ID = p_batch_id
              AND THRESHOLD_EXCEEDED = 1
        )
        SELECT
            w.SENSOR_ID,
            MAX(w.LOCATION_ID) KEEP (DENSE_RANK LAST ORDER BY w.WINDOW_START) AS LOCATION_ID,
            w.SOURCE_MAC,
            w.DESTINATION_BSSID,
            MAX(w.SSID) KEEP (DENSE_RANK LAST ORDER BY w.WINDOW_START) AS SSID,
            TRUNC(CAST(w.WINDOW_START AS DATE)) AS ALERT_DATE,
            MIN(w.WINDOW_START) AS FIRST_WINDOW_START,
            MAX(w.WINDOW_START) AS LAST_WINDOW_START,
            SUM(w.BYTES) AS TOTAL_BYTES,
            COUNT(*) AS WINDOW_COUNT,
            MAX(w.BYTES) AS MAX_BYTES_PER_WINDOW
        FROM WL_BW_WINDOWS w
        JOIN batch_keys k
          ON k.SENSOR_ID = w.SENSOR_ID
         AND k.SOURCE_MAC = w.SOURCE_MAC
         AND k.DESTINATION_BSSID = w.DESTINATION_BSSID
         AND k.ALERT_DATE = TRUNC(CAST(w.WINDOW_START AS DATE))
        WHERE w.THRESHOLD_EXCEEDED = 1
        GROUP BY
            w.SENSOR_ID,
            w.SOURCE_MAC,
            w.DESTINATION_BSSID,
            TRUNC(CAST(w.WINDOW_START AS DATE))
    ) src
    ON (
        tgt.SENSOR_ID = src.SENSOR_ID
        AND tgt.SOURCE_MAC = src.SOURCE_MAC
        AND tgt.DESTINATION_BSSID = src.DESTINATION_BSSID
        AND tgt.ALERT_DATE = src.ALERT_DATE
    )
    WHEN MATCHED THEN UPDATE SET
        tgt.LOCATION_ID = src.LOCATION_ID,
        tgt.SSID = src.SSID,
        tgt.FIRST_WINDOW_START = src.FIRST_WINDOW_START,
        tgt.LAST_WINDOW_START = src.LAST_WINDOW_START,
        tgt.TOTAL_BYTES = src.TOTAL_BYTES,
        tgt.WINDOW_COUNT = src.WINDOW_COUNT,
        tgt.MAX_BYTES_PER_WINDOW = src.MAX_BYTES_PER_WINDOW,
        tgt.UPDATED_AT = SYSTIMESTAMP
    WHEN NOT MATCHED THEN INSERT (
        SENSOR_ID, LOCATION_ID, SOURCE_MAC, DESTINATION_BSSID, SSID,
        ALERT_DATE, FIRST_WINDOW_START, LAST_WINDOW_START,
        TOTAL_BYTES, WINDOW_COUNT, MAX_BYTES_PER_WINDOW
    ) VALUES (
        src.SENSOR_ID, src.LOCATION_ID, src.SOURCE_MAC, src.DESTINATION_BSSID,
        src.SSID, src.ALERT_DATE, src.FIRST_WINDOW_START, src.LAST_WINDOW_START,
        src.TOTAL_BYTES, src.WINDOW_COUNT, src.MAX_BYTES_PER_WINDOW
    );
    COMMIT;
END WL_BW_MERGE_ALERTS;
